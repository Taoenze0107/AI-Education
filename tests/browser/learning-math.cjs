const assert = require("node:assert/strict");
const learning = require("../../app/static/learning-math.js");
const close = (actual, expected, tolerance = 1e-10) => assert.ok(Math.abs(actual - expected) <= tolerance);
close(learning.convert(20, "mA").value, .02);
close(learning.convert(1, "μF").value, 1e-6);
assert.equal(learning.convert(Infinity, "ms"), null);
assert.equal(learning.convert(1, "unsupported"), null);
assert.throws(() => learning.numberList(""));
assert.throws(() => learning.numberList("1, NaN"));
assert.deepEqual(learning.numberList("1，2 3"), [1, 2, 3]);
const rc = learning.rc({ times: [0, 5, 10, 20], voltage: [0, 1.967, 3.160602794, 4.323], resistance: 10000, capacitance: 1e-6, finalVoltage: 5 });
close(rc.tau, .01);
close(rc.measuredTau, .01, 1e-8);
const nonzero = learning.rc({ times: [0, 5, 10], voltage: [1, 2, 3], resistance: 10000, capacitance: 1e-6, finalVoltage: 5 });
close(nonzero.threshold, 1 + (1 - Math.exp(-1)) * 4);
assert.equal(nonzero.measuredTau, null);
assert.throws(() => learning.rc({ times: [0, 0, 10], voltage: [0, 1, 2], resistance: 10000, capacitance: 1e-6, finalVoltage: 5 }));
assert.throws(() => learning.rc({ times: [0, 5, 10], voltage: [0, 1], resistance: 10000, capacitance: 1e-6, finalVoltage: 5 }));
const pend = learning.pendulum({ length: 1, count: 10, times: [20.05, 20.06, 20.07] });
close(pend.meanPeriod, 2.006);
close(pend.sd, .001);
close(pend.g, 4 * Math.PI ** 2 / 2.006 ** 2);
assert.throws(() => learning.pendulum({ length: 1, count: 1.5, times: [20, 21] }));
assert.throws(() => learning.pendulum({ length: 1, count: 10, times: [20] }));
assert.throws(() => learning.pendulum({ length: 0, count: 10, times: [20, 21] }));
console.log("Learning calculations: conversion, RC interpolation and pendulum edge cases passed.");
